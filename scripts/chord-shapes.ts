/**
 * Boils chords-db's guitar and ukulele chords down to what the song view needs: one shape per
 * chord (the library's first, its most common voicing), keyed by root pitch and suffix, into
 * `src/shared/chordpro/chordShapes.ts` (D132). Run again only to take a new version of it:
 *   node scripts/chord-shapes.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import guitar from '@tombatossals/chords-db/lib/guitar.json' with { type: 'json' };
import ukulele from '@tombatossals/chords-db/lib/ukulele.json' with { type: 'json' };
import library from '@tombatossals/chords-db/package.json' with { type: 'json' };

const OUT = 'src/shared/chordpro/chordShapes.ts';
const LICENSE = createRequire(import.meta.url).resolve('@tombatossals/chords-db/LICENSE');

const PITCH: Record<string, number> = {
  C: 0,
  Csharp: 1,
  Db: 1,
  D: 2,
  Eb: 3,
  E: 4,
  F: 5,
  Fsharp: 6,
  Gb: 6,
  G: 7,
  Ab: 8,
  A: 9,
  Bb: 10,
  B: 11,
};
const NOTE_PITCH: Record<string, number> = {
  C: 0,
  'C#': 1,
  Db: 1,
  D: 2,
  'D#': 3,
  Eb: 3,
  E: 4,
  F: 5,
  'F#': 6,
  Gb: 6,
  G: 7,
  'G#': 8,
  Ab: 8,
  A: 9,
  Bb: 10,
  B: 11,
};

type Library = {
  chords: Record<
    string,
    { suffix: string; positions: { frets: number[]; baseFret: number }[] }[]
  >;
};

/** "/E" → "/4", "m/B" → "m/11": a slash chord's bass by pitch, as the song view looks it up. */
function suffixKey(suffix: string): string | null {
  const slash = /^(m?)\/(.+)$/.exec(suffix);
  if (!slash) {
    return suffix;
  }
  const bass = NOTE_PITCH[slash[2] as string];
  return bass === undefined ? null : `${slash[1]}/${bass}`;
}

function shapes(instrument: Library) {
  const out: Record<string, [number, number[]]> = {};
  for (const [key, chords] of Object.entries(instrument.chords)) {
    const pitch = PITCH[key];
    if (pitch === undefined) {
      throw new Error(`Unknown key in chords-db: ${key}`);
    }
    for (const chord of chords) {
      const suffix = suffixKey(chord.suffix);
      const first = chord.positions[0];
      if (suffix !== null && first) {
        out[`${pitch}:${suffix}`] = [first.baseFret, first.frets];
      }
    }
  }
  return out;
}

const license = readFileSync(LICENSE, 'utf8').trim();
const data = {
  guitar: shapes(guitar as Library),
  ukulele: shapes(ukulele as Library),
};

writeFileSync(
  OUT,
  `/*
 * Generated by scripts/chord-shapes.ts from chords-db ${library.version}
 * (https://github.com/tombatossals/chords-db). Don't edit: run the script again.
 *
${license
  .split('\n')
  .map((line) => ` * ${line}`.trimEnd())
  .join('\n')}
 */

/** Instrument → "rootPitch:suffix" → [base fret, frets low to high, -1 not played]. */
export const CHORD_SHAPES: Record<
  'guitar' | 'ukulele',
  Record<string, [number, number[]]>
> = ${JSON.stringify(data)};
`,
);
console.log(
  `${OUT}: ${Object.keys(data.guitar).length} guitar, ${Object.keys(data.ukulele).length} ukulele shapes`,
);
